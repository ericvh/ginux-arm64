#!/bin/sh
# Print a C table from x86-64 syscall numbers to aarch64 ones, for the
# aarch64 build of tests/fixtures/native-fixture.c. Each entry is the aarch64
# number plus one; zero marks an x86-64 number with no aarch64 counterpart.
# The source of truth is the pair list in crates/ginux-core.
set -eu

root=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
map=$root/crates/ginux-core/src/syscall_map.rs

echo "/* Generated by scripts/aarch64-syscall-header.sh. Do not edit. */"
echo "static const unsigned short aarch64_number[] = {"
awk '
    /^    \([0-9]+, [0-9]+\),/ {
        gsub(/[(),]/, "")
        printf "    [%d] = %d + 1,\n", $2, $1
        rows++
    }
    END { if (rows < 300) { print "too few syscall pairs: " rows > "/dev/stderr"; exit 1 } }
' "$map"
echo "};"
