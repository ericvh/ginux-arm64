#!/bin/sh
# Build the measured AArch64 controller ELF and the boot manifest that names it.
set -eu

root=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
src="$root/boot/efi/aarch64-controller.S"
ldscript="$root/boot/efi/aarch64-controller.ld"
elf="$root/boot/efi/aarch64-controller.elf"
manifest_rs="$root/boot/efi/src/aarch64_measured.rs"
generated="$root/boot/efi/src/generated_boot.rs"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

lld=$(find /usr/local/rustup /usr -path '*/gcc-ld/ld.lld' -type f 2>/dev/null | head -n 1 || true)
if [ -z "$lld" ]; then
    echo "ld.lld is required to link the aarch64 controller" >&2
    exit 1
fi

clang --target=aarch64-linux-gnu -c -o "$work/controller.o" "$src"
"$lld" -m aarch64elf -nostdlib -static -s -z max-page-size=4096 -T "$ldscript" -o "$elf" "$work/controller.o"

python3 - "$generated" "$elf" "$manifest_rs" <<'PY'
import hashlib
import pathlib
import re
import struct
import sys

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

generated = pathlib.Path(sys.argv[1]).read_text()
elf = pathlib.Path(sys.argv[2]).read_bytes()
output = pathlib.Path(sys.argv[3])

match = re.search(
    r"pub\(crate\) static BOOT_MANIFEST: \[u8; (\d+)\] = \[(.*?)\];",
    generated,
    re.S,
)
if match is None:
    raise SystemExit("BOOT_MANIFEST array not found")
manifest = bytes(
    int(part, 16)
    for part in re.findall(r"0x([0-9a-fA-F]{2})", match.group(2))
)
expected = int(match.group(1))
if len(manifest) != expected or len(manifest) < 152:
    raise SystemExit(f"manifest length {len(manifest)} != {expected}")

digest = hashlib.sha256(elf).digest()
manifest = bytearray(manifest)
struct.pack_into("<Q", manifest, 112, len(elf))
manifest[120:152] = digest

seed = bytes.fromhex(
    "9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60"
)
key = Ed25519PrivateKey.from_private_bytes(seed)
public = key.public_key().public_bytes_raw()
expected_public = bytes.fromhex(
    "d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a"
)
if public != expected_public:
    raise SystemExit("development ed25519 key does not match the kernel")
signature = key.sign(bytes(manifest))
manifest_digest = hashlib.sha256(bytes(manifest)).digest()


def rust_array(name, data, public):
    width = 16
    rows = []
    for start in range(0, len(data), width):
        chunk = data[start : start + width]
        rows.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    body = "\n".join(rows)
    visibility = "pub(crate) " if public else ""
    return f"{visibility}const {name}: [u8; {len(data)}] = [\n{body}\n];"


text = "\n".join(
    [
        "// @generated by scripts/aarch64-controller.sh; do not edit.",
        "// The AArch64 controller ELF replaces the x86_64 controller in the",
        "// measured-boot manifest for the aarch64 UEFI image only.",
        rust_array("BOOT_MANIFEST", bytes(manifest), True),
        rust_array("BOOT_MANIFEST_SHA256", manifest_digest, True),
        rust_array("BOOT_MANIFEST_SIGNATURE", signature, True),
        "",
    ]
)
output.write_text(text)
print(f"controller elf {len(elf)} bytes sha256 {digest.hex()}")
PY
